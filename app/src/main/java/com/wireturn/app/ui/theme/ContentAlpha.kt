package com.wireturn.app.ui.theme

/**
 * Общие альфа-токены для приглушённого контента, чтобы визуальный вес одинаковых
 * по смыслу элементов (второстепенные иконки/текст, disabled-состояния) не расходился
 * по разным экранам из-за случайных чисел.
 */
object ContentAlpha {
    /** Disabled-контент (M3 baseline). */
    const val disabled = 0.38f

    /** Второстепенные, но читаемые иконки/текст (плейсхолдеры, подписи, неактивные акценты). */
    const val secondary = 0.6f
}
